export const HOT_GENRES = INITIAL_HOT_GENRES;

const STORAGE_KEY = 'dao_tam_genres_v3';

import { safeSetItem, safeGetItem } from '../utils/safeStorage';

export function getStoredGenres(): GenreItem[] {
  if (typeof window === 'undefined') return INITIAL_HOT_GENRES;
  try {
    const raw = safeGetItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length >= INITIAL_HOT_GENRES.length) return parsed;
    }
  } catch (e) {
    console.warn('Failed to parse stored genres', e);
  }
  return INITIAL_HOT_GENRES;
}

export function saveGenres(genres: GenreItem[]): void {
  if (typeof window === 'undefined') return;
  safeSetItem(STORAGE_KEY, JSON.stringify(genres));
}

/**
 * Tự động tạo thể loại mới đúng chuẩn cấu trúc GenreItem
 */
export function createGenreItem(name: string, description?: string): GenreItem {
  const trimmed = name.trim();
  const slug = trimmed
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\w\s-]/g, '')
    .replace(/\s+/g, '-');

  const id = `genre-${slug || Date.now()}`;

  // Tự động phân bổ icon tương thích ngữ nghĩa
  let iconName = 'Tag';
  const lower = trimmed.toLowerCase();
  if (lower.includes('tiên') || lower.includes('tu')) iconName = 'Mountain';
  else if (lower.includes('kiếm') || lower.includes('võ')) iconName = 'Swords';
  else if (lower.includes('ma') || lower.includes('quỷ') || lower.includes('linh')) iconName = 'Ghost';
  else if (lower.includes('yêu') || lower.includes('tình') || lower.includes('hôn')) iconName = 'Heart';
  else if (lower.includes('thực') || lower.includes('ăn')) iconName = 'Smile';
  else if (lower.includes('hoàng') || lower.includes('cung') || lower.includes('vương')) iconName = 'Crown';
  else if (lower.includes('thời') || lower.includes('xuyên') || lower.includes('sinh')) iconName = 'Hourglass';
  else if (lower.includes('thú') || lower.includes('mèo') || lower.includes('chó')) iconName = 'PawPrint';
  else if (lower.includes('hệ thống') || lower.includes('game') || lower.includes('võng')) iconName = 'Cpu';
  else if (lower.includes('khoa') || lower.includes('huyễn') || lower.includes('tinh')) iconName = 'Flame';

  return {
    id,
    name: trimmed,
    iconName,
    description: description || `Thể loại ${trimmed} thuộc thư viện Đạo Tâm`,
    isCustom: true,
  };
}
